// Turns the raw PTT dump into the shipped data files.
//
//   input   raw/ptt-dump.json        one entry per province, as harvested
//   output  data/index.json          provinces + district names, loaded eagerly
//           data/provinces/<code>.mjs  one module per province, on demand
//
// The per-province payload is a single string rather than nested JSON: it is
// smaller over the wire and splitting it beats parsing an array of objects.
//
//   SEYHAN;AKKAPI MAH.:01040|ALTINŞEHİR MAH.:01170
//   CEYHAN;...

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const INPUT = join(root, "raw", "ptt-dump.json");
const DATA = join(root, "data");

// A name carrying one of these would break the encoding.
const DELIMITERS = [";", "|", ":", "\n"];
const trSort = (a, b) => a.toLocaleLowerCase("tr").localeCompare(b.toLocaleLowerCase("tr"), "tr");

function assertEncodable(value, where) {
  for (const d of DELIMITERS) {
    if (value.includes(d)) throw new Error(`Delimiter ${JSON.stringify(d)} in ${where}: ${value}`);
  }
}

if (!existsSync(INPUT)) {
  console.error(`Missing ${INPUT}. Harvest the PTT data first.`);
  process.exit(1);
}

const dump = JSON.parse(readFileSync(INPUT, "utf8"));
const input = Array.isArray(dump) ? dump : Object.values(dump);

rmSync(DATA, { recursive: true, force: true });
mkdirSync(join(DATA, "provinces"), { recursive: true });

const index = [];
const warnings = [];
const sizes = [];
let districtCount = 0;
let neighbourhoodCount = 0;
let multiCount = 0;

for (const province of input.sort((a, b) => a.code - b.code)) {
  assertEncodable(province.name, `province ${province.code}`);

  const districts = [...province.districts].sort((a, b) => trSort(a.name, b.name));
  const lines = [];

  for (const district of districts) {
    assertEncodable(district.name, `district ${province.name}/${district.name}`);

    const neighbourhoods = [...district.neighbourhoods].sort((a, b) => trSort(a.name, b.name));
    const parts = [];

    for (const n of neighbourhoods) {
      assertEncodable(n.name, `neighbourhood ${province.name}/${district.name}/${n.name}`);
      // Most neighbourhoods have one postal code, a few hundred have several;
      // all of them are kept, comma separated, so nothing is silently dropped.
      const codes = n.postalCodes.filter((code) => /^\d{5}$/.test(code));
      if (codes.length !== n.postalCodes.length) {
        warnings.push(
          `${province.name}/${district.name}/${n.name}: unexpected postal code in ${JSON.stringify(n.postalCodes)}`,
        );
      }
      if (codes.length === 0) warnings.push(`${province.name}/${district.name}/${n.name}: no postal code`);
      if (codes.length > 1) multiCount++;
      parts.push(`${n.name}:${codes.join(",")}`);
    }

    lines.push(`${district.name};${parts.join("|")}`);
    neighbourhoodCount += neighbourhoods.length;
  }

  districtCount += districts.length;

  const payload = lines.join("\n");
  writeFileSync(
    join(DATA, "provinces", `${province.code}.mjs`),
    `// ${province.name} — generated by scripts/build.mjs, do not edit\nexport default ${JSON.stringify(payload)};\n`,
  );

  sizes.push({
    code: province.code,
    name: province.name,
    districts: districts.length,
    neighbourhoods: districts.reduce((a, d) => a + d.neighbourhoods.length, 0),
    rawKB: +(Buffer.byteLength(payload) / 1024).toFixed(1),
    gzipKB: +(gzipSync(payload).length / 1024).toFixed(1),
  });

  index.push({ code: province.code, name: province.name, districts: districts.map((d) => d.name) });
}

const indexJson = JSON.stringify({
  source: "PTT (ptt.gov.tr/posta-kodu)",
  date: new Date().toISOString().slice(0, 10),
  counts: { provinces: index.length, districts: districtCount, neighbourhoods: neighbourhoodCount },
  provinces: index,
});
writeFileSync(join(DATA, "index.json"), indexJson);

sizes.sort((a, b) => b.gzipKB - a.gzipKB);
const total = sizes.reduce((a, s) => a + s.rawKB, 0);

console.log(`provinces ${index.length} · districts ${districtCount} · neighbourhoods ${neighbourhoodCount}`);
console.log(`${multiCount} neighbourhood(s) carry more than one postal code`);
console.log(
  `index.json ${(Buffer.byteLength(indexJson) / 1024).toFixed(1)} kB raw · ${(gzipSync(indexJson).length / 1024).toFixed(1)} kB gzip`,
);
console.log(`province chunks ${total.toFixed(0)} kB raw in total`);
console.log("\nlargest chunks (what a visitor downloads after picking a province):");
for (const s of sizes.slice(0, 10)) {
  console.log(
    `  ${s.name.padEnd(12)} ${String(s.districts).padStart(3)} districts ${String(s.neighbourhoods).padStart(5)} neighbourhoods  ${String(s.rawKB).padStart(6)} kB raw  ${String(s.gzipKB).padStart(5)} kB gzip`,
  );
}
// What a visitor actually pays: index.json plus the one province they pick.
// The budget guards the worst province, not the average, because that is the
// only number a user can be unlucky enough to hit.
const BUDGET_KB = 30;
const gzipped = sizes.map((s) => s.gzipKB).sort((a, b) => a - b);
const at = (p) => gzipped[Math.min(gzipped.length - 1, Math.floor(gzipped.length * p))];
const worst = sizes[0];

console.log("\nper-province gzip: median %s kB · p90 %s kB · largest %s kB (%s)", at(0.5), at(0.9), worst.gzipKB, worst.name);
console.log(`${gzipped.filter((kb) => kb < 10).length}/${gzipped.length} provinces under 10 kB`);
console.log(`typical visit: index + median province = ${(gzipSync(indexJson).length / 1024 + at(0.5)).toFixed(1)} kB`);
console.log(
  `\ngate: largest province chunk ${worst.gzipKB} kB gzip (${worst.name}) — ${worst.gzipKB <= BUDGET_KB ? "PASS" : "FAIL"} against the ${BUDGET_KB} kB budget`,
);
if (worst.gzipKB > BUDGET_KB) process.exitCode = 1;

if (warnings.length) {
  console.log(`\n${warnings.length} warning(s):`);
  for (const w of warnings.slice(0, 20)) console.log(`  ${w}`);
  if (warnings.length > 20) console.log(`  ... and ${warnings.length - 20} more`);
}
